CONFIG = os.path.join(os.environ.get("XDG_CONFIG_HOME") or os.path.join(HOME, ".config"), "chezmoi",
                      "chezmoi.toml")
CHECKOUT = os.path.join(HOME, ".local/share/fw13-hypr")  # install.sh's own clone (CHECKOUT)
INSTALLER = os.path.join(CHECKOUT, "install.sh")

# Table → keys, in the order .chezmoi.toml.tmpl writes them.
SCHEMA = {"chromium": ("api_key", "client_id", "client_secret"),
          "restic": ("repository", "password"),
          "ollama": ("api_key",),
          "restic_creds": ("aws_access_key_id", "aws_secret_access_key", "aws_default_region")}
# Tables without a prompt: written only while one of their values is set, keys sorted and unaligned (the template's
# `range` over the table), so a re-init renders the same text.
OPTIONAL = ("restic_creds",)
# S3 (AWS, Backblaze B2, Wasabi, R2, MinIO) is the only cloud backend whose keys this page stores; sftp:, rest:
# (user:pass in the URL), rclone: and local paths need none. Native b2:/azure:/gs:/swift: would need keys of their own.
S3_KEYS = ("aws_access_key_id", "aws_secret_access_key", "aws_default_region")
S3_REQUIRED = ("aws_access_key_id", "aws_secret_access_key")
UNSUPPORTED = ("b2:", "azure:", "gs:", "swift:")
NATIVE_KEY_PREFIXES = ("B2_", "AZURE_", "GOOGLE_", "OS_", "ST_")  # their own env keys, if added to the env file by hand

# Values end up unquoted in environment.d / EnvironmentFile lines: no whitespace, quotes, $, `, #, \ or newlines.
VALUE_RE = re.compile(r"[A-Za-z0-9._~:/@+=%,_-]{0,512}")
USERINFO_RE = re.compile(r"(?i)([a-z][a-z0-9+.-]*://)[^/@\s]*@")  # rest:https://user:pass@host/ → rest:https://host/

