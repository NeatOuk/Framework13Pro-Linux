"""Setup-time choices the installer asked once: Chromium sign-in keys, Ollama Cloud key, restic backups, login
shell; plus read-only facts about the dotfiles checkout and what the installer set up.

Values live in ~/.config/chezmoi/chezmoi.toml ([data.chromium] / [data.restic] / [data.ollama], the shape
.chezmoi.toml.tmpl renders, plus the optional [data.restic_creds] with S3 keys, which has no prompt and the template
writes back as it is); chezmoi turns them into private_ files. Secrets never go into argv, logs, store.py
or a returned message: status() reports only "set" and a length, restic gets them through env=, and every error
text passes through _redact(). Calls may block (chezmoi, restic, polkit): run them from a worker thread.
"""
