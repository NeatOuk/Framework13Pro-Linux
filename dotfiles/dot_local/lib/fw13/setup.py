def dotfiles_state():
    """{"source", "remote", "rev", "dirty", "installer"}; "" where unknown."""
    st = {"source": "", "remote": "", "rev": "", "dirty": False, "installer": os.path.isfile(INSTALLER)}
    exe = chezmoi_bin()
    if exe:
        rc, out, _e = _run(exe, "source-path", timeout=10)
        st["source"] = out.strip() if rc == 0 and os.path.isdir(out.strip()) else ""
    src = st["source"]
    if src and shutil.which("git"):
        rc, out, _e = _run("git", "-C", src, "remote", "get-url", "origin", timeout=5)
        remote = display_repository(out.strip()) if rc == 0 else ""
        if remote.startswith("git@"):
            remote = remote[4:].replace(":", "/", 1)
        st["remote"] = re.sub(r"^[a-z+]+://", "", remote).removesuffix(".git")
        rc, out, _e = _run("git", "-C", src, "rev-parse", "--short", "HEAD", timeout=5)
        st["rev"] = out.strip() if rc == 0 else ""
        rc, out, _e = _run("git", "-C", src, "status", "--porcelain", "--untracked-files=no", timeout=5)
        st["dirty"] = rc == 0 and bool(out.strip())
    return st


def installed_state():
    """[(label, value)] of what the installer set up. Each probe is quick and read-only."""
    rows = []
    dm = os.path.realpath("/etc/systemd/system/display-manager.service")
    dm = os.path.basename(dm).removesuffix(".service") if os.path.exists(dm) else ""
    rows.append(("Login", {"gdm": "GDM", "sddm": "SDDM", "greetd": "greetd + tuigreet", "lightdm": "LightDM"}
                 .get(dm, dm or "none (text console)")))
    rc, out, _e = _run("rpm", "-q", "--qf", "%{VENDOR}", "hyprland", timeout=10)
    if rc == 0:
        m = re.search(r"Copr - user (\S+)", out)
        rows.append(("Hyprland", f"from COPR {m.group(1)}" if m else f"from {out.strip() or 'unknown vendor'}"))
    else:
        rows.append(("Hyprland", "not installed as a package"))
    rc, out, _e = _run("flatpak", "remotes", "--user", "--columns=name", timeout=10)
    rows.append(("Flathub", "added (no apps installed by fw13)" if rc == 0 and "flathub" in out.split()
                 else "not added"))
    return rows


def fingerprints():
    """Number of enrolled fingers, or None when fprintd isn't there / no reader."""
    user = pwd.getpwuid(os.getuid()).pw_name
    rc, out, err = _run("fprintd-list", user, timeout=10)
    if rc == 127 or "no devices" in (out + err).lower():
        return None
    return len(re.findall(r"^\s*-\s*#\d+:", out, re.M))


def timeshift_state():
    """"btrfs"/"rsync" + whether Timeshift's own schedule is active, or "" when Timeshift isn't set up."""
    try:
        with open("/etc/timeshift/timeshift.json") as f:
            conf = json.load(f)
    except (OSError, ValueError):
        return ""
    mode = "btrfs" if str(conf.get("btrfs_mode", "")).lower() == "true" else "rsync"
    if not conf.get("backup_device_uuid"):
        return ""
    # Timeshift schedules itself: with a schedule_* flag on it writes /etc/cron.d/timeshift-hourly, run by crond.
    flags = any(str(v).lower() == "true" for k, v in conf.items() if k.startswith("schedule_"))
    rc, _o, _e = _run("systemctl", "is-enabled", "--quiet", "crond.service", timeout=10)
    on = flags and os.path.exists("/etc/cron.d/timeshift-hourly") and rc == 0
    return f"{mode}, {'scheduled' if on else 'not scheduled'}"
